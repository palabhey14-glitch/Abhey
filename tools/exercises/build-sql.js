// Writes supabase/migrations/2026-10-26-exercises.sql from the starter
// library in site/app/js/exercises.js, so the app and the database agree.
//   node tools/exercises/build-sql.js
'use strict';
const fs = require('fs');
const path = require('path');
const X = require('../../site/app/js/exercises.js');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const muscles = Object.keys(X.MUSCLES);

const rows = X.LIBRARY.map((ex) => `  (${q(ex.name)}, ${arr(ex.primary)}, ${ex.secondary.length ? arr(ex.secondary) : "'{}'::text[]"}, ${q(ex.equipment)})`);

const sql = `-- Exercise library for the coach's training plan builder.
-- Run once on the live database:
-- Supabase dashboard -> SQL Editor -> New query -> paste all -> Run.
-- Safe to run again: the starter list is upserted by name.
--
-- Generated by tools/exercises/build-sql.js from site/app/js/exercises.js.
-- Each exercise lists the muscles it mainly works (primary) and the ones it
-- also works (secondary); the app draws them on a body diagram.

create table if not exists public.exercises (
  id                uuid primary key default gen_random_uuid(),
  name              text not null check (length(trim(name)) between 1 and 120),
  primary_muscles   text[] not null check (cardinality(primary_muscles) between 1 and 6),
  secondary_muscles text[] not null default '{}',
  equipment         text check (equipment is null or length(equipment) <= 40),
  is_custom         boolean not null default false,
  created_at        timestamptz not null default now(),
  constraint exercises_muscles_check check (
    primary_muscles <@ array[${muscles.map(q).join(', ')}]::text[]
    and secondary_muscles <@ array[${muscles.map(q).join(', ')}]::text[]
  )
);
create unique index if not exists exercises_name_key on public.exercises (lower(name));

alter table public.exercises enable row level security;
revoke all on public.exercises from anon;
grant select, insert, update, delete on public.exercises to authenticated;

drop policy if exists "signed-in users read exercises" on public.exercises;
create policy "signed-in users read exercises" on public.exercises
  for select to authenticated using (true);
drop policy if exists "coach adds exercises" on public.exercises;
create policy "coach adds exercises" on public.exercises
  for insert to authenticated with check ((select public.is_coach()));
drop policy if exists "coach updates exercises" on public.exercises;
create policy "coach updates exercises" on public.exercises
  for update to authenticated
  using ((select public.is_coach())) with check ((select public.is_coach()));
drop policy if exists "coach deletes exercises" on public.exercises;
create policy "coach deletes exercises" on public.exercises
  for delete to authenticated using ((select public.is_coach()));

-- Starter list (${rows.length} exercises).
insert into public.exercises (name, primary_muscles, secondary_muscles, equipment) values
${rows.join(',\n')}
on conflict (lower(name)) do update
  set primary_muscles = excluded.primary_muscles,
      secondary_muscles = excluded.secondary_muscles,
      equipment = excluded.equipment
  where not public.exercises.is_custom;
`;

const out = path.join(__dirname, '../../supabase/migrations/2026-10-26-exercises.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(process.cwd(), out)} (${rows.length} exercises)`);
