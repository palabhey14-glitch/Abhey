// Where imported rows go:
//   rest   Supabase (PostgREST) with the service-role key, in batches
//   sql    a .sql file of upserts, for psql or a local database
//   ndjson one JSON row per line, for checking or for sample files
'use strict';
const fs = require('node:fs');

const COLUMNS = ['source', 'source_id', 'source_version', 'source_url', 'name', 'brand', 'barcode', 'countries', 'category',
  'basis', 'kcal', 'protein_g', 'carbs_g', 'fat_g', 'fibre_g', 'sugars_g', 'sodium_mg', 'quality', 'portions', 'notes',
  'needs_review', 'retired_at', 'import_tag', 'last_seen_at'];

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

class RestSink {
  constructor({ url, key, fetchImpl }) {
    if (!url || !key) throw new Error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (Supabase -> Project Settings -> API). Never commit the service key.');
    this.base = url.replace(/\/$/, '') + '/rest/v1';
    this.key = key;
    this.fetch = fetchImpl || fetch;
  }

  async call(path, method, body, prefer) {
    for (let attempt = 1; ; attempt++) {
      const res = await this.fetch(this.base + path, {
        method,
        headers: { apikey: this.key, Authorization: `Bearer ${this.key}`, 'Content-Type': 'application/json', Prefer: prefer || 'return=minimal' },
        body: body === undefined ? undefined : JSON.stringify(body),
      });
      if (res.ok) return res.status === 204 ? null : res.json().catch(() => null);
      const text = await res.text();
      if (attempt < 5 && (res.status >= 500 || res.status === 429)) {
        await sleep(1000 * 2 ** attempt);
        continue;
      }
      throw new Error(`${method} ${path} failed: ${res.status} ${text.slice(0, 300)}`);
    }
  }

  upsert(rows) {
    return this.call('/foods?on_conflict=source,source_id', 'POST', rows, 'resolution=merge-duplicates,return=minimal');
  }

  async startRun(run) {
    await this.call('/import_runs?on_conflict=tag', 'POST', run, 'resolution=merge-duplicates,return=minimal');
  }

  updateRun(tag, patch) {
    return this.call(`/import_runs?tag=eq.${encodeURIComponent(tag)}`, 'PATCH', patch);
  }

  // Marks rows of this source and dataset that the finished run did not see.
  async retire({ source, versionPrefix, before, countries }) {
    let q = `/foods?source=eq.${source}&retired_at=is.null&last_seen_at=lt.${encodeURIComponent(before)}`;
    if (versionPrefix) q += `&source_version=like.${encodeURIComponent(versionPrefix + '*')}`;
    if (countries && countries.length) q += `&countries=ov.${encodeURIComponent('{' + countries.join(',') + '}')}`;
    const rows = await this.call(q, 'PATCH', { retired_at: new Date().toISOString() }, 'return=representation');
    return rows ? rows.length : 0;
  }

  close() {}
}

function sqlLiteral(v) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(sqlLiteral).join(',')}]::text[]`;
  if (typeof v === 'object') return `${sqlLiteral(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

class SqlSink {
  constructor({ out }) {
    this.fd = fs.openSync(out, 'w');
    fs.writeSync(this.fd, '-- Generated by tools/food-import. Run with psql against your database.\nbegin;\n');
  }

  upsert(rows) {
    const value = (r, c) => {
      if (c === 'countries') return sqlLiteral(r[c] || []);
      if (c === 'portions' || c === 'notes') return r[c] === null || r[c] === undefined ? (c === 'portions' ? "'[]'::jsonb" : 'null') : `${sqlLiteral(JSON.stringify(r[c]))}::jsonb`;
      return sqlLiteral(r[c]);
    };
    const values = rows.map((r) => `(${COLUMNS.map((c) => value(r, c)).join(',')})`);
    const set = COLUMNS.filter((c) => c !== 'source' && c !== 'source_id').map((c) => `${c} = excluded.${c}`).join(', ');
    fs.writeSync(this.fd, `insert into public.foods (${COLUMNS.join(',')}) values\n${values.join(',\n')}\non conflict (source, source_id) do update set ${set};\n`);
  }

  startRun(run) {
    fs.writeSync(this.fd, `insert into public.import_runs (source, tag, dataset, mode) values (${sqlLiteral(run.source)}, ${sqlLiteral(run.tag)}, ${sqlLiteral(run.dataset)}, ${sqlLiteral(run.mode)}) on conflict (tag) do nothing;\n`);
  }

  updateRun(tag, patch) {
    const sets = Object.entries(patch).map(([k, v]) => `${k} = ${sqlLiteral(v)}`).join(', ');
    fs.writeSync(this.fd, `update public.import_runs set ${sets} where tag = ${sqlLiteral(tag)};\n`);
  }

  retire({ source, versionPrefix, before, countries }) {
    fs.writeSync(this.fd, `update public.foods set retired_at = now() where source = ${sqlLiteral(source)} and retired_at is null and last_seen_at < ${sqlLiteral(before)}${
      versionPrefix ? ` and source_version like ${sqlLiteral(versionPrefix + '%')}` : ''}${countries && countries.length ? ` and countries && ${sqlLiteral(countries)}` : ''};\n`);
    return null;
  }

  close() {
    fs.writeSync(this.fd, 'commit;\n');
    fs.closeSync(this.fd);
  }
}

class NdjsonSink {
  constructor({ out }) {
    this.fd = fs.openSync(out, 'w');
  }
  upsert(rows) {
    for (const r of rows) {
      const { import_tag, last_seen_at, retired_at, ...rest } = r;
      fs.writeSync(this.fd, JSON.stringify(rest) + '\n');
    }
  }
  startRun() {}
  updateRun() {}
  retire() {
    return null;
  }
  close() {
    fs.closeSync(this.fd);
  }
}

module.exports = { RestSink, SqlSink, NdjsonSink, COLUMNS, sqlLiteral };
